#!/usr/bin/env bash
# Generates scenarios/51-tracker-window.scn (inputs only; goldens are never
# hand-written). Usage: bash gen-tracker-window.sh > scenarios/51-tracker-window.scn
set -eu
echo "# The Tracker's window: the rate uses the last 12 steps; past 64 steps it"
echo "# drops the oldest 32. Generated by ../gen-tracker-window.sh."
echo "# Format: see ../README.md (or the header of 10-flags.scn)."
echo
echo "=== tracker-window-speeds-up-and-drains"
echo "# 30 steps of 1 % every 60 s, then 40 steps of 1 % every 30 s."
echo "@1700000000 poll"
echo "ups.status OB DISCHRG"
echo "battery.charge 100"
echo "battery.charge.low 5"
t=1700000000
c=100
for i in $(seq 1 70); do
  if [ "$i" -le 30 ]; then t=$((t + 60)); else t=$((t + 30)); fi
  c=$((c - 1))
  echo "@$t poll+"
  echo "battery.charge $c"
  case $i in 2 | 12 | 13 | 30 | 31 | 35 | 42 | 43 | 64 | 65 | 66 | 70) echo "@$t estimate" ;; esac
done
echo "@$((t + 44)) estimate"
echo "@$((t + 46)) estimate"
